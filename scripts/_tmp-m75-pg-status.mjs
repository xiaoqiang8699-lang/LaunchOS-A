import { createRequire } from 'node:module';
import { existsSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
for (const file of [resolve(root, '.env'), resolve(root, '.secrets/alpha-data-plane.env')]) {
  if (!existsSync(file)) continue;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#') || !t.includes('=')) continue;
    const i = t.indexOf('=');
    const k = t.slice(0, i).trim();
    let v = t.slice(i + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    if (process.env[k] === undefined) process.env[k] = v;
  }
}
const requireApi = createRequire(resolve(root, 'apps/api/package.json'));
const { PrismaClient } = requireApi('@launchos/database');
const { decryptCredential, resolveServerSshUsername, shellCommand } = requireApi('@launchos/shared');
const { RemoteRunner } = requireApi('@launchos/remote-runner');
const prisma = new PrismaClient();
const TARGET_HOST = '116.62.198.184';
const server = await prisma.serverInstance.findFirst({
  where: { OR: [{ id: 'cmuma9i480001rij49yv4yw2q' }, { host: TARGET_HOST, scope: 'PLATFORM_MANAGED' }] },
});
const username = resolveServerSshUsername({ serverUsername: server.username, provider: server.provider });
const password = decryptCredential(server.credentialEncrypted);
const runner = new RemoteRunner();
await runner.connect({ host: server.host, port: server.port, username, password });

for (const cmd of [
  'podman ps -a --filter name=launchos-alpha-postgres --format "{{.Names}} {{.Status}}"',
  'podman logs --tail 40 launchos-alpha-postgres 2>&1',
  'podman exec launchos-alpha-postgres pg_isready -U launchos_alpha -d launchos 2>&1 || true',
  'podman inspect launchos-alpha-api --format "{{.State.Status}} {{.ImageName}}" 2>&1',
]) {
  const r = await runner.execute(shellCommand(cmd), { timeoutMs: 60000 });
  console.log('CMD', cmd);
  console.log((r.stdout || '') + (r.stderr || ''));
  console.log('exit', r.exitCode);
}

await runner.disconnect();
await prisma.$disconnect();
